"""Hardware in the loop, step 1 (2026-11-10): what the board needs to take raw feature frames one at a time,
and the host reference its outputs must match.

For one int8-I/O network of the highD or exiD tasks (datasets/<ds>/results/deploy/<stem>.tflite) it writes
  firmware/build/stream/<stem>/stream_cfg.h   window length, feature count, the per-feature offset and range
      of unas/highd_dataset.py (training statistics: x_scaled = (x - lo) / (hi - lo + 1e-12), float32) and
      the network's input quantization (q = round half to even of x_scaled / scale + zero point, saturated);
  firmware/build/stream/<stem>/reference.npz  the test split as frame sequences in raw units, the int8 frames
      the board should compute from them, and the int8 outputs of the TFLite interpreter for every window
      (26 per 35-frame scenario), with labels, crossing frames and the I/O quantization.
Both stay in firmware/build/ (not versioned): they hold training statistics and test data of licensed
datasets. The board's arithmetic in firmware/h7b3/main.c (STREAM_MODE) is the float32 arithmetic used here.

LCIR (datasets/dmir/results/deploy/lcir_*_int8_io.tflite, 2026-11-11): the test windows are 50 frames of 31
features at 10 Hz, one decision per window, so each window is one 50-frame sequence. The board first limits
every feature to its training range (as every LCIR evaluation does, prepare_deploy.prep), then applies the
min-max scaling of a network searched on scaled inputs (offsets and spans of its deploy record; none for
raw-input networks) and quantizes. The header then also defines STREAM_CLAMP with the training range.

Whole LCIR drives (2026-11-11): a copy of an LCIR network's file named
datasets/dmir/data/sessions/sessions_<file name> selects the raw sessions of the official test drivers
(datasets/dmir/session_stream.py build) instead of the test windows: every frame of every session in raw
units, a decision on every frame from the 50th on. The board's table then holds the provider's
normalization (recovered per task, pickle = a * raw + b), followed by the network's own min-max scaling
if it has one, and the training range in raw units. With LCIR_SPLIT=val in the environment the sessions
of the official validation drivers are taken instead (2026-11-12, for choices that must not be made on
the test drivers); their files go to firmware/build/stream/<stem>_val/. LCIR_SPLIT=own takes sessions of one's own
(datasets/dmir/session_stream.py own, e.g. recorded with the lab's simulator) the same way.

Simulated traffic (a copy of a highD network's file under datasets/carla/, scenarios of
datasets/carla/prepare_carla.py): the scaling uses highD's training statistics, as the deployed network does.

Run in the WSL NAS venv (TensorFlow), from anywhere:
  ~/dmir_nas/bin/python /mnt/c/Projects/PhD/DIMIR/unas/hil_prepare.py \
      datasets/highd/results/deploy/<stem>_int8_io.tflite
"""
from __future__ import annotations

import json
import os
import pickle
import sys
from pathlib import Path

import numpy as np
import tensorflow as tf

ROOT = Path(__file__).resolve().parent.parent
IN_LEN, SEQ_LEN = 10, 35
N_SLIDES = SEQ_LEN - IN_LEN + 1


def frames(ds: str, split: str):
    z = np.load(ROOT / "datasets" / ds / "data" / "prepared" / f"{split}.npz")
    return z["feats"].astype(np.float32), z["label"].astype(np.int64), z["cross_idx"].astype(np.int64)


def c_floats(v) -> str:
    return ", ".join(f"{float(x):.9e}f" for x in np.asarray(v, np.float32))


def interface(tfl: Path, in_len: int, n_feat: int):
    it = tf.lite.Interpreter(model_path=str(tfl))
    it.allocate_tensors()
    inp, out = it.get_input_details()[0], it.get_output_details()[0]
    if inp["dtype"] != np.int8 or tuple(inp["shape"][1:]) != (in_len, n_feat):
        sys.exit(f"{tfl.name}: expected an int8 input of shape (1, {in_len}, {n_feat}), got {inp['dtype']} {inp['shape']}")
    return it, inp, out


def header(tfl: Path, in_len: int, lo, span, si, zi, clamp=None) -> str:
    text = (f"/* Generated by unas/hil_prepare.py for {tfl.name}. Training statistics: not versioned. */\n"
            f"#define STREAM_IN_LEN {in_len}\n#define STREAM_N_FEAT {len(lo)}\n"
            f"#define STREAM_IN_SCALE {float(np.float32(si)):.9e}f\n#define STREAM_IN_ZP {int(zi)}\n"
            f"static const float stream_lo[STREAM_N_FEAT] = {{{c_floats(lo)}}};\n"
            f"static const float stream_span[STREAM_N_FEAT] = {{{c_floats(span)}}};\n")
    if clamp is not None:
        text += ("#define STREAM_CLAMP 1\n"
                 f"static const float stream_cmin[STREAM_N_FEAT] = {{{c_floats(clamp[0])}}};\n"
                 f"static const float stream_cmax[STREAM_N_FEAT] = {{{c_floats(clamp[1])}}};\n")
    return text


def lcir(tfl: Path) -> None:
    """One 50-frame sequence per LCIR test window; the board clamps, scales and quantizes."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from prepare_deploy import LAYOUT

    rec = json.loads((tfl.parent / (tfl.stem.rsplit("_int8_io", 1)[0] + "_deploy.json")).read_text())
    task = rec["task"]
    folder, sfx, is_cls, _ = LAYOUT[task]
    root = Path(os.environ.get("DMIR_DATA_ROOT", ROOT / "datasets" / "dmir" / "data")) / folder

    def rd(s, xy):
        with open(root / f"{xy}_{s}_{sfx}.pkl", "rb") as f:
            return pickle.load(f)

    xtr = rd("train", "x").astype(np.float32)
    feats = rd("test", "x").astype(np.float32)               # as recorded: not clipped
    label = rd("test", "y")
    label = label.astype(np.int64).reshape(-1) if is_cls else label.astype(np.float32).reshape(-1)
    in_len, n_feat = feats.shape[1:]
    cmin, cmax = xtr.min(axis=(0, 1)), xtr.max(axis=(0, 1))
    if rec.get("input_scaling", "raw") == "minmax":
        lo, span = np.asarray(rec["scale_lo"], np.float32), np.asarray(rec["scale_span"], np.float32)
    else:
        lo, span = np.zeros(n_feat, np.float32), np.ones(n_feat, np.float32)
    it, inp, out = interface(tfl, in_len, n_feat)
    (si, zi), (so, zo) = inp["quantization"], out["quantization"]
    n_out = int(np.prod(out["shape"][1:]))
    xs = (np.clip(feats, cmin, cmax) - lo) / span            # float32, the board's arithmetic
    assert xs.dtype == np.float32
    q = np.clip(np.rint(xs / np.float32(si) + np.float32(zi)), -128, 127).astype(np.int8)
    ref = np.empty((len(q), 1, n_out), np.int8)
    for s in range(len(q)):
        it.set_tensor(inp["index"], q[s][None])
        it.invoke()
        ref[s, 0] = it.get_tensor(out["index"]).reshape(-1)

    dest = ROOT / "firmware" / "build" / "stream" / tfl.stem
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "stream_cfg.h").write_text(header(tfl, in_len, lo, span, si, zi, clamp=(cmin, cmax)), encoding="utf-8")
    np.savez_compressed(dest / "reference.npz", feats=feats, q=q, ref=ref, label=label,
                        in_scale=np.float32(si), in_zp=int(zi), out_scale=np.float32(so), out_zp=int(zo),
                        lo=lo, span=span, cmin=cmin, cmax=cmax, in_len=in_len, seq_len=in_len, tflite=tfl.name)
    deq = (ref[:, 0].astype(np.float32) - zo) * so
    summary = {"tflite": tfl.name, "task": task, "windows": len(q), "frames": int(len(q) * in_len),
               "outputs": n_out, "in_quant": [float(si), int(zi)], "out_quant": [float(so), int(zo)],
               "input_scaling": rec.get("input_scaling", "raw"),
               "frames_outside_training_range": int((feats != np.clip(feats, cmin, cmax)).any(-1).sum()),
               "deploy_record": rec["variants"]["int8_io"]}
    if is_cls:
        summary["accuracy"] = round(float((deq.argmax(-1) == label).mean()), 5)
    else:
        summary["rmse"] = round(float(np.sqrt(((deq[:, 0] - label) ** 2).mean())), 5)
    print(json.dumps(summary))
    print(f"wrote {dest / 'stream_cfg.h'} and {dest / 'reference.npz'}")


def lcir_sessions(tfl: Path) -> None:
    """Whole drives of the LCIR test drivers, frame by frame, for one network. LCIR_SPLIT=val takes the
    validation drivers' sessions (session_stream.py build val) and writes to <stem>_val."""
    split = os.environ.get("LCIR_SPLIT", "test")
    tag = "" if split == "test" else f"_{split}"
    deploy = tfl.stem[len("sessions_"):].rsplit("_int8_io", 1)[0]
    rec = json.loads((ROOT / "datasets" / "dmir" / "results" / "deploy" / f"{deploy}_deploy.json").read_text())
    task = rec["task"]
    base = ROOT / "datasets" / "dmir" / "data" / "stream"
    norm = json.loads((base / f"{task}_norm.json").read_text())
    z = np.load(base / f"{task}_sessions{tag}.npz")
    feats, lens = z["feats"].astype(np.float32), z["seq_lens"].astype(np.int64)
    n_feat, in_len, big = feats.shape[1], 50, 1e30
    a, b = np.array(norm["a"]), np.array(norm["b"])
    tmin, tmax = np.array(norm["train_min"]), np.array(norm["train_max"])
    moving = a != 0
    safe = np.where(moving, a, 1.0)
    lo = np.where(moving, -b / safe, -b * big)               # pickle value = (raw - lo) / span
    span = np.where(moving, 1.0 / safe, big)
    c1, c2 = (tmin - b) / safe, (tmax - b) / safe            # the training range in raw units
    fmax = float(np.finfo(np.float32).max)
    cmin = np.where(moving, np.minimum(c1, c2), -fmax)
    cmax = np.where(moving, np.maximum(c1, c2), fmax)
    if rec.get("input_scaling", "raw") == "minmax":          # the network's own scaling of the pickle value
        mlo, mspan = np.array(rec["scale_lo"], float), np.array(rec["scale_span"], float)
        const = (b - mlo) / mspan
        lo = np.where(moving, lo + span * mlo, -const * big)
        span = np.where(moving, span * mspan, big)
    lo, span, cmin, cmax = (v.astype(np.float32) for v in (lo, span, cmin, cmax))

    it, inp, out = interface(tfl, in_len, n_feat)
    (si, zi), (so, zo) = inp["quantization"], out["quantization"]
    n_out = int(np.prod(out["shape"][1:]))
    xs = (np.clip(feats, cmin, cmax) - lo) / span            # float32, the board's arithmetic
    assert xs.dtype == np.float32
    q = np.clip(np.rint(xs / np.float32(si) + np.float32(zi)), -128, 127).astype(np.int8)
    starts = np.concatenate([[0], np.cumsum(lens)[:-1]])
    wins = [(int(s) + k) for s, n in zip(starts, lens) for k in range(int(n) - in_len + 1)]
    ref = np.empty((len(wins), n_out), np.int8)
    for w, s in enumerate(wins):
        it.set_tensor(inp["index"], q[s:s + in_len][None])
        it.invoke()
        ref[w] = it.get_tensor(out["index"]).reshape(-1)

    dest = ROOT / "firmware" / "build" / "stream" / (tfl.stem + tag)
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "stream_cfg.h").write_text(header(tfl, in_len, lo, span, si, zi, clamp=(cmin, cmax)), encoding="utf-8")
    last = np.array(wins) + in_len - 1                       # the frame a window ends on
    np.savez_compressed(dest / "reference.npz", feats=feats, q=q, ref=ref, seq_lens=lens, names=z["names"],
                        ttlc=z["ttlc"], direction=z["direction"], window_last_frame=last, events=z["events"],
                        in_scale=np.float32(si), in_zp=int(zi), out_scale=np.float32(so), out_zp=int(zo),
                        lo=lo, span=span, cmin=cmin, cmax=cmax, in_len=in_len, task=task, tflite=tfl.name)
    deq = (ref.astype(np.float32) - zo) * so
    ttlc, direction = z["ttlc"][last], z["direction"][last]
    summary = {"tflite": tfl.name, "task": task, "sessions": len(lens), "frames": int(lens.sum()),
               "windows": len(wins), "minutes": round(float(lens.sum()) / 600, 1),
               "input_scaling": rec.get("input_scaling", "raw"), "deploy_record": rec["variants"]["int8_io"]}
    scored = ~np.isnan(ttlc)
    if n_out == 3:
        summary["frame_accuracy_all_sessions"] = round(float((deq.argmax(-1)[scored] == direction[scored]).mean()), 5)
    else:
        want = 1 if task == "regression_lcr" else 2
        sel = scored & (direction == want)
        summary["rmse_before_own_lane_changes"] = round(float(np.sqrt(((deq[sel, 0] - ttlc[sel]) ** 2).mean())), 5)
        summary["frames_before_own_lane_changes"] = int(sel.sum())
    print(json.dumps(summary))
    print(f"wrote {dest / 'stream_cfg.h'} and {dest / 'reference.npz'}")


def main(tfl_arg: str) -> None:
    tfl = (ROOT / tfl_arg).resolve() if not Path(tfl_arg).is_absolute() else Path(tfl_arg)
    ds = tfl.relative_to(ROOT).parts[1]
    if ds == "dmir":
        return lcir_sessions(tfl) if tfl.parent.name == "sessions" else lcir(tfl)
    if ds not in ("highd", "exid", "carla"):
        sys.exit("streaming is set up for the highD and exiD scenarios and the LCIR windows")
    # simulated traffic (datasets/carla) is given to a highD network as deployed: highD's statistics
    train, _, _ = frames("highd" if ds == "carla" else ds, "train")
    n_feat = train.shape[-1]
    lo = train.reshape(-1, n_feat).min(0)
    hi = train.reshape(-1, n_feat).max(0)
    span = hi - lo + 1e-12                                  # as unas/highd_dataset.py
    assert lo.dtype == span.dtype == np.float32
    record = tfl.parent / (tfl.stem.rsplit("_int8_io", 1)[0] + "_deploy.json")
    gain = json.loads(record.read_text()).get("input_gain") if record.exists() else None
    if gain is not None:                                    # equalized network: the gain goes into the span
        span = (span / np.asarray(gain, np.float32)).astype(np.float32)

    it, inp, out = interface(tfl, IN_LEN, n_feat)
    (si, zi), (so, zo) = inp["quantization"], out["quantization"]
    n_out = int(np.prod(out["shape"][1:]))

    feats, label, cross = frames(ds, "test")
    xs = (feats - lo) / span                                # float32, the board's arithmetic
    q = np.clip(np.rint(xs / np.float32(si) + np.float32(zi)), -128, 127).astype(np.int8)
    ref = np.empty((len(q), N_SLIDES, n_out), np.int8)
    for s in range(len(q)):
        for k in range(N_SLIDES):
            it.set_tensor(inp["index"], q[s, k:k + IN_LEN][None])
            it.invoke()
            ref[s, k] = it.get_tensor(out["index"]).reshape(-1)

    dest = ROOT / "firmware" / "build" / "stream" / tfl.stem
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "stream_cfg.h").write_text(header(tfl, IN_LEN, lo, span, si, zi), encoding="utf-8")
    np.savez_compressed(dest / "reference.npz", feats=feats, q=q, ref=ref, label=label, cross=cross,
                        in_scale=np.float32(si), in_zp=int(zi), out_scale=np.float32(so), out_zp=int(zo),
                        lo=lo, span=span, in_len=IN_LEN, seq_len=SEQ_LEN, tflite=tfl.name)

    deq = (ref.astype(np.float32) - zo) * so
    summary = {"tflite": tfl.name, "scenarios": len(q), "windows": int(len(q) * N_SLIDES), "outputs": n_out,
               "in_quant": [float(si), int(zi)], "out_quant": [float(so), int(zo)]}
    if n_out == 3:
        summary["window_accuracy"] = round(float((deq.argmax(-1) == label[:, None]).mean()), 4)
    print(json.dumps(summary))
    print(f"wrote {dest / 'stream_cfg.h'} and {dest / 'reference.npz'}")


if __name__ == "__main__":
    main(sys.argv[1])
