"""Hardware in the loop, step 1 (2026-11-11): where the board and the TFLite reference differ, ask ST's C
model on the host.

For a network replayed with `hil_stream.py --rate 0 --save`, the windows whose board outputs differ from
the reference of unas/hil_prepare.py (TFLite interpreter) are run through the C model that ST Edge AI
generates, compiled for the PC (`stedgeai validate --mode host`), with the reference's int8 inputs. The
same number of windows on which board and reference agree goes along as a control (at least 32). If the
C model on the host returns the board's values, a difference lies between ST's kernels and the TFLite
interpreter, not in the board, its preprocessing or the link.

  .venv\\Scripts\\python unas/hil_host_check.py [--board] datasets/<ds>/results/deploy/<stem>_int8_io.tflite [...]

--board also gives the differing windows (and eight control windows) to the board as int8 inputs, without
its own preprocessing (firmware/h7b3, make CHECK=1, outputs read over SWD). That separates the two places
a difference can come from: if the board, fed the reference's int8 window, returns the streamed value, its
network code differs from the other implementation and its preprocessing is not involved; if it returns
the reference's value, the int8 window it built from the raw frames was a different one.

One JSON line per network goes to datasets/<ds>/results/hil/hil_host_check.jsonl (counts only).
"""
from __future__ import annotations

import json
import re
import shutil
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import local_bench as lb                                    # noqa: E402  (tool paths, run)

ROOT = lb.ROOT


def board_direct(tfl: Path, x: np.ndarray) -> np.ndarray:
    """Outputs of the board for int8 input windows x given to the network as they are (make CHECK=1)."""
    tag = tfl.stem
    gen = lb.FW / "build" / "gen" / tag
    gen.mkdir(parents=True, exist_ok=True)
    lb.run([lb.STEDGEAI, "generate", "--model", tfl, "--target", "stm32", "--name", "network", "--c-api", "legacy",
            "--output", gen, "--workspace", lb.FW / "build" / "ws" / tag])
    hdr = lb.FW / "build" / "check" / "check_io.h"
    hdr.parent.mkdir(parents=True, exist_ok=True)
    with open(hdr, "w", encoding="ascii") as f:
        f.write("/* Generated by unas/hil_host_check.py: test windows, not versioned. */\n")
        f.write(f"#define CHECK_N {len(x)}\nstatic const int8_t check_in[CHECK_N][{x[0].size}] = {{\n")
        for w in x:
            f.write("{" + ",".join(str(int(v)) for v in w.reshape(-1)) + "},\n")
        f.write("};\n")
    lb.run([lb.MAKE, "-B", f"GEN=../build/gen/{tag}", "CHECK=1"], cwd=lb.FW / "h7b3")
    elf = lb.FW / "build" / "h7b3check" / tag / "fw.elf"
    sn = lb.find_stlink("STM32H7B3I-DK")
    lb.run([lb.CLI, "-c", "port=SWD", f"sn={sn}", "mode=UR", "-w", elf, "-v", "-rst"])
    lb.read_result(elf, sn, timeout_s=300)
    sym = {}
    for ln in lb.run([lb.GCC_BIN / "arm-none-eabi-nm.exe", "-S", elf]).splitlines():
        parts = ln.split()
        if len(parts) == 4 and parts[-1] in ("g_check_out", "g_check_done"):
            sym[parts[-1]] = (int(parts[0], 16), int(parts[1], 16))
    t0 = time.time()
    while "42454E43" not in lb.run([lb.CLI, "-c", "port=SWD", f"sn={sn}", "mode=HOTPLUG", "-r32",
                                    hex(sym["g_check_done"][0]), "4"]).upper():
        if time.time() - t0 > 120:
            raise TimeoutError("the board did not finish the check")
        time.sleep(1.0)
    addr, size = sym["g_check_out"]
    dump = lb.run([lb.CLI, "-c", "port=SWD", f"sn={sn}", "mode=HOTPLUG", "-r8", hex(addr), str(size)])
    vals = []
    for line in dump.splitlines():
        m = re.match(r"\s*0x[0-9A-Fa-f]{8}\s*:\s*((?:[0-9A-Fa-f]{2}\s*)+)$", line)
        if m:
            vals += [int(v, 16) for v in m.group(1).split()]
    if len(vals) < size:
        raise RuntimeError(f"read {len(vals)} of {size} output bytes from the board")
    return np.frombuffer(bytes(vals[:size]), dtype=np.int8).reshape(len(x), -1)


def check(tfl: Path, direct: bool = False) -> dict:
    ds = tfl.relative_to(ROOT).parts[1]
    folder = lb.FW / "build" / "stream" / tfl.stem
    ref = np.load(folder / "reference.npz")
    board = np.load(folder / "board_out_rate0.npz")["outs"]
    want = ref["ref"][:len(board)]
    in_len = int(ref["in_len"]) if "in_len" in ref else 10
    drives = "seq_lens" in ref                              # whole drives: one flat list of windows
    differ = np.argwhere((board != want).any(-1))
    same = np.argwhere((board == want).all(-1))
    rng = np.random.default_rng(0)
    control = same[rng.choice(len(same), size=min(len(same), max(32, len(differ))), replace=False)]
    rows = np.concatenate([differ, control]) if len(differ) else control
    if drives:
        last = ref["window_last_frame"]
        x = np.stack([ref["q"][last[w] - in_len + 1:last[w] + 1] for (w,) in rows]).astype(np.int8)
    else:
        x = np.stack([ref["q"][s, k:k + in_len] for s, k in rows]).astype(np.int8)

    work = lb.FW / "build" / "hostcheck" / tfl.stem
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    np.savez(work / "in.npz", m_inputs_1=x)
    lb.run([lb.STEDGEAI, "validate", "--model", tfl, "--target", "stm32", "--mode", "host", "--name", "network",
            "--valinput", work / "in.npz", "--batches", str(len(x)),
            "--output", work / "out", "--workspace", work / "ws"])
    z = np.load(work / "out" / "network_val_io.npz")
    c = z["c_outputs_1"].reshape(len(z["c_outputs_1"]), -1)
    if len(c) != len(x) or not (z["m_inputs_1"].reshape(x.shape) == x).all():
        raise RuntimeError(f"{tfl.name}: the host run used {len(c)} of {len(x)} windows")
    b = np.stack([board[tuple(r)] for r in rows])
    t = np.stack([want[tuple(r)] for r in rows])
    nd = len(differ)
    rec = {"model": tfl.name, "windows_replayed": int(len(board) if drives else board.shape[0] * board.shape[1]),
           "differing_windows": nd,
           "differing": {"host_c_equals_board": int((c[:nd] == b[:nd]).all(-1).sum()),
                         "host_c_equals_tflite": int((c[:nd] == t[:nd]).all(-1).sum()),
                         "max_abs_lsb_board_vs_tflite": int(np.abs(b[:nd].astype(int) - t[:nd].astype(int)).max()) if nd else 0},
           "control": {"windows": int(len(rows) - nd),
                       "host_c_equals_board": int((c[nd:] == b[nd:]).all(-1).sum())}}
    if direct and nd:
        k = nd + min(8, len(rows) - nd)
        d = board_direct(tfl, x[:k])
        rec["board_given_the_int8_window"] = {
            "differing_windows": {"equals_streamed_board": int((d[:nd] == b[:nd]).all(-1).sum()),
                                  "equals_host_c": int((d[:nd] == c[:nd]).all(-1).sum()),
                                  "equals_tflite": int((d[:nd] == t[:nd]).all(-1).sum())},
            "control_windows": {"windows": int(k - nd), "equals_streamed_board": int((d[nd:] == b[nd:k]).all(-1).sum())}}
    rec["utc"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    out = ROOT / "datasets" / ds / "results" / "hil" / "hil_host_check.jsonl"
    with open(out, "a", encoding="utf-8") as f:
        f.write(json.dumps(rec) + "\n")
    print(json.dumps(rec))
    return rec


if __name__ == "__main__":
    for arg in [a for a in sys.argv[1:] if a != "--board"]:
        check((ROOT / arg).resolve(), direct="--board" in sys.argv)
